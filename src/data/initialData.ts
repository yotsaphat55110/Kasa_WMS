// Initial inventory state linking products to warehouses & zones
export const generateInitialInventory = (): InventoryItem[] => {
  const items: InventoryItem[] = [];
  
  initialProducts.forEach((product, idx) => {
    let warehouseId = 'wh-01';
    let zoneId = 'z-101';

    // Route liquids and acids to WH-2, Boiler/RO to WH-3
    if (product.characters.toLowerCase().includes('liquid') || product.name.toLowerCase().includes('acid') || product.name.includes('น้ำ')) {
      warehouseId = 'wh-02';
      zoneId = idx % 2 === 0 ? 'z-201' : 'z-202';
    }
    if (product.id.startsWith('p-5')) {
      warehouseId = 'wh-03';
      if (product.id === 'p-52' || product.id === 'p-53') zoneId = 'z-301';
      else if (product.id === 'p-54' || product.id === 'p-55') zoneId = 'z-302';
      else zoneId = 'z-303';
    }

    // Good vs Damaged
    const totalGood = 800 + (idx * 37) % 1500;
    const damaged = (idx % 7 === 0) ? 15 + (idx % 4) * 10 : 0; // Some items have damaged stock

    items.push({
      id: `inv-${product.id}-${warehouseId}`,
      productId: product.id,
      warehouseId,
      zoneId,
      quantityGood: totalGood,
      quantityDamaged: damaged,
      lastUpdated: new Date(Date.now() - (idx * 3600000)).toISOString(),
      lastAdjustedBy: 'สมชาย สายเคมี (EMP-002)'
    });
  });

  return items;
};

